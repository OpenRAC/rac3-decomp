#!/usr/bin/env python3
"""names.py: readable names for the address-named symbols (docs/contributing/names.md).

    python3 tools/names.py header                 # config/names.tsv -> include/names.h
    python3 tools/names.py check                  # the table is valid and include/names.h is current
    python3 tools/names.py func_L01_004EE4E0      # look a symbol or a name up
    python3 tools/names.py hero_update

Every symbol keeps its address name (func_XXXXXXXX, func_LNN_XXXXXXXX, D_XXXXXXXX): the build and
the tools read addresses out of it. include/names.h lists the readable names as `#define hero_update func_L01_004EE4E0` lines for
lookup. It is NOT included by common.h or any C: `#define` aliases are not allowed in matched C,
so source keeps the address names.

config/names.tsv has one row per named symbol: symbol, name, tier, source (where the name comes
from, docs/contributing/names.md "Sources"), evidence, alternatives.
Rows of tier `recovered` (the original identifier) and `descriptive` (a name with evidence) go into
names.h; `candidate` rows (weaker, or a name that is already an identifier in src/) do not.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TABLE = os.path.join(ROOT, "config", "names.tsv")
HEADER = os.path.join(ROOT, "include", "names.h")
COLUMNS = ["symbol", "name", "tier", "source", "evidence", "alternatives"]
TIERS = ("recovered", "descriptive", "candidate")
IN_HEADER = ("recovered", "descriptive")
SYMBOL = re.compile(r"^(func|D)_(L\d\d_)?[0-9A-F]{8}$")
IDENT = re.compile(r"^[A-Za-z_]\w*$")


def read_table(path=TABLE):
    rows = []
    with open(path) as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            cols = line.rstrip("\n").split("\t")
            cols += [""] * (len(COLUMNS) - len(cols))
            rows.append(dict(zip(COLUMNS, cols)))
    return rows


def header_text(rows):
    out = ["/* include/names.h: generated by tools/names.py header from config/names.tsv; do not edit.",
           " * Readable names for address-named symbols (docs/contributing/names.md). */",
           "#ifndef NAMES_H", "#define NAMES_H", ""]
    for r in sorted((r for r in rows if r["tier"] in IN_HEADER), key=lambda r: r["symbol"]):
        out.append("#define %s %s" % (r["name"], r["symbol"]))
    out += ["", "#endif /* NAMES_H */", ""]
    return "\n".join(out)


def known_symbols():
    """Function symbols the tables know: the level catalogue's names and the core programs'."""
    known = set()
    with open(os.path.join(ROOT, "config", "levels", "functions.tsv")) as f:
        for line in f:
            if not line.startswith("#"):
                known.add(line.split("\t", 1)[0])
    with open(os.path.join(ROOT, "config", "inventory.tsv")) as f:
        for line in f:
            if not line.startswith("#"):
                cols = line.split("\t")
                known.add("func_" + cols[2])
    return known


def check(rows):
    errors = []
    known = known_symbols()
    seen_sym, seen_name = {}, {}
    for r in rows:
        s, n = r["symbol"], r["name"]
        if not SYMBOL.match(s):
            errors.append("%s: not an address name" % s)
        if s.startswith("func_") and s not in known:
            errors.append("%s: no such function in config/levels/functions.tsv or config/inventory.tsv" % s)
        if not IDENT.match(n) or SYMBOL.match(n):
            errors.append("%s: name %r is not a readable C identifier" % (s, n))
        if r["tier"] not in TIERS:
            errors.append("%s: tier %r is not one of %s" % (s, r["tier"], ", ".join(TIERS)))
        if not r["source"]:
            errors.append("%s: no source (docs/contributing/names.md, Sources)" % s)
        if not r["evidence"]:
            errors.append("%s: no evidence" % s)
        if s in seen_sym:
            errors.append("%s: two rows" % s)
        seen_sym[s] = r
        if r["tier"] in IN_HEADER:
            if n in seen_name:
                errors.append("%s: name %s is also %s's" % (s, n, seen_name[n]))
            seen_name[n] = s
    if not os.path.exists(HEADER) or open(HEADER).read() != header_text(rows):
        errors.append("include/names.h is out of date: python3 tools/names.py header")
    return errors


def main(argv):
    if not argv:
        sys.exit(__doc__)
    rows = read_table()
    if argv[0] == "header":
        with open(HEADER, "w", newline="\n") as f:
            f.write(header_text(rows))
        print("include/names.h: %d names" % sum(r["tier"] in IN_HEADER for r in rows))
    elif argv[0] == "check":
        errors = check(rows)
        for e in errors:
            print("error: " + e)
        print("%d rows, %s" % (len(rows), "%d error(s)" % len(errors) if errors else "OK"))
        return 1 if errors else 0
    else:
        for key in argv:
            hits = [r for r in rows if key in (r["symbol"], r["name"]) or key in r["alternatives"].split(",")]
            for r in hits:
                print("\t".join(r[c] for c in COLUMNS))
            if not hits:
                print("%s: not in config/names.tsv" % key)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
