#!/usr/bin/env python3
"""resolve_symbols.py: write a program's config/<program>/symbol_addrs_resolved.txt.

The linker script reads that file (INPUT(...)): every func_/D_/jtbl_ name the assembly or the C
uses that no object defines, at the address its name gives (D_00143950_b, D_001DA0D0_003BDBA0: another spelling of
an address under another C type, is D_00143950's address). Names are addresses in this
repository, so the file is generated, never edited:

    python3 tools/resolve_symbols.py --target all

It reads asm/ (tools/setup_asm.py writes it) and src/, so run it after setup_asm.py and after
changing C. Symbols with real names (the libgcc entry points the library C calls, such as
__muldi3 or dpcmp) are kept by hand at the end of the file, after the NAMED line; this tool keeps
that part as it is.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import srcfiles as sf  # noqa: E402
import targets  # noqa: E402

NAME = re.compile(r"\b((?:func|D|jtbl)_([0-9A-Fa-f]{1,8}))((?:_[A-Za-z0-9]+)*)\b")
LABEL = re.compile(r"^\s*(?:glabel|dlabel|jlabel|alabel|\.globl)\s+(\w+)", re.M)
NAMED = "/* named symbols, kept by hand (tools/resolve_symbols.py leaves them as they are) */"
C_DEF = re.compile(r"(?m)^[A-Za-z_][\w \*]*?\b(func_[0-9A-Fa-f]{8})\s*\([^;{]*\)[^;{]*\{")


def asm_files(t):
    others = {os.path.normpath(o.path("asm_root")) for o in targets.ALL.values() if o is not t}
    root = t.path("asm_root")
    for d, subdirs, fs in os.walk(root):
        subdirs[:] = [s for s in subdirs if os.path.normpath(os.path.join(d, s)) not in others
                      and not (t.name in targets.TARGETS and os.path.normpath(os.path.join(d, s)) == os.path.join(targets.ROOT, "asm", "levels"))
                      # the NTSC-U disc's assembly (tools/asm_build.py --version us) is another disc's
                      and os.path.normpath(os.path.join(d, s)) != os.path.join(targets.ROOT, "asm", "us")]
        for f in fs:
            if f.endswith(".s"):
                yield os.path.join(d, f)


def main():
    t = targets.from_argv(allow_all=True)
    used, defined = set(), set()
    for p in asm_files(t):
        s = open(p, errors="ignore").read()
        defined |= set(LABEL.findall(s))
        used |= {m.group(1) + m.group(3) for m in NAME.finditer(s)}
    text = sf.strip_comments(sf.read_all(ROOT, sf.read_file_list()))
    defined |= set(C_DEF.findall(text))
    used |= {m.group(1) + m.group(3) for m in NAME.finditer(text)}
    lines = ["/* %s: names the code uses that no object defines, at their addresses" % t.name,
             "   (generated by tools/resolve_symbols.py; do not edit). */"]
    for n in sorted(used - defined):
        hexpart = NAME.match(n).group(2)
        lines.append("%s = 0x%08X;" % (n, int(hexpart, 16)))
    count = len(lines) - 2
    path = t.path("symbols_resolved")
    old = open(path).read() if os.path.exists(path) else ""
    if NAMED in old:
        lines.append("")
        lines.append(NAMED + old.split(NAMED, 1)[1].rstrip("\n"))
    open(path, "w", newline="\n").write("\n".join(lines) + "\n")
    print("%s: %d names" % (t.name, count))


if __name__ == "__main__":
    main()
