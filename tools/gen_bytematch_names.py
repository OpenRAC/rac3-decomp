#!/usr/bin/env python3
"""gen_bytematch_names.py: include/bytematch_names.h, the source name of every reported function.

    python3 tools/gen_bytematch_names.py           # write the header
    python3 tools/gen_bytematch_names.py --check   # the header is current (CI, tests/check_repository.py)

ByteMatch (https://bytematch.dev/docs/source-linking) shows a function's code by finding where
the repository defines it under the name the progress report uses. The reports here use names
src/ doesn't define: NTSC-U's report names functions by NTSC-U addresses while src/ is PAL's
(config/us/map.tsv), a level's copy of shared code is defined once under its catalogue name
(config/levels/functions.tsv, config/us/levels/functions.tsv), and boot_elf's front-end
functions are written once, as frontbin's (config/frontend_pairs.tsv). The header ties each
report name src/ doesn't define to the name it does, one `#define <report name> <source name>`
per line, for the names the committed reports (progress/) use. Nothing includes it, so it can't
change the build. tools/progress.py --write regenerates it with the reports, and --check fails
when it is out of date.
"""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "include" / "bytematch_names.h"
SRC = ROOT / "src"
REPORTS = [ROOT / "progress" / "report.json", ROOT / "progress" / "us" / "report.json"]
TABLES = {
    "pal_levels": ROOT / "config" / "levels" / "functions.tsv",
    "us_levels": ROOT / "config" / "us" / "levels" / "functions.tsv",
    "us_map": ROOT / "config" / "us" / "map.tsv",
    "pal_pairs": ROOT / "config" / "frontend_pairs.tsv",
    "us_pairs": ROOT / "config" / "us" / "frontend_pairs.tsv",
}
NAME = re.compile(r"\bfunc_[0-9A-Za-z_]+\b")


def rows(path: Path):
    if not path.exists():
        return
    for line in path.read_text().splitlines():
        if line and not line.startswith("#"):
            yield line.split("\t")


def copies(path: Path) -> dict[str, str]:
    """A level catalogue's copies: func_L<level>_<address> of each place -> the row's name."""
    out = {}
    for c in rows(path):
        if len(c) < 7:
            continue
        for place in c[6].split(","):
            level, _, address = place.partition(":")
            if level and address:
                out[f"func_L{level}_{address}"] = c[0]
    return out


def source_names() -> set[str]:
    """Every func_ name src/ mentions: definitions, INCLUDE_ASM and LINKER_REMNANT lines."""
    names = set()
    for f in SRC.rglob("*"):
        if f.suffix in (".c", ".h", ".s", ".inc") and f.is_file():
            names.update(NAME.findall(f.read_text(errors="replace")))
    return names


def header() -> str:
    pal_copy = copies(TABLES["pal_levels"])
    us_copy = copies(TABLES["us_levels"])
    us_to_pal = {c[2]: c[0] for c in rows(TABLES["us_map"]) if len(c) > 2 and c[0] != c[2]}
    # boot_elf's front-end functions are frontbin's code (tools/level_catalogue.py): either side's name.
    pairs = {}
    for key in ("pal_pairs", "us_pairs"):
        for c in rows(TABLES[key]):
            if len(c) > 1:
                pairs.setdefault(c[0], c[1])
                pairs.setdefault(c[1], c[0])
    have = source_names()

    def source_of(name: str) -> str | None:
        # The name itself; a PAL level copy's catalogue name; NTSC-U's PAL name, directly or by
        # its own catalogue name, and that name's catalogue name in turn.
        pal = us_to_pal.get(name) or us_to_pal.get(us_copy.get(name, "")) or us_to_pal.get(pairs.get(name, ""))
        for candidate in (name, pal_copy.get(name), pal, pal_copy.get(pal or ""), pairs.get(name), pairs.get(pal or "")):
            if candidate and candidate in have:
                return candidate
        return None

    # Only the names the committed reports use: each distinct function once, not every copy.
    reported = set()
    for path in REPORTS:
        if path.exists():
            for unit in json.loads(path.read_text()).get("units", []):
                reported.update(f["name"] for f in unit.get("functions", []))
    lines = []
    for name in sorted(reported):
        target = source_of(name)
        if target and target != name:
            lines.append(f"#define {name} {target}")
    return (
        "/* include/bytematch_names.h: generated by tools/gen_bytematch_names.py, not included anywhere.\n"
        " * The name src/ defines each reported function under, for ByteMatch's source view\n"
        " * (https://bytematch.dev/docs/source-linking). Regenerate after the tables change. */\n"
        + "\n".join(lines)
        + "\n"
    )


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--check", action="store_true", help="fail if the header isn't current")
    a = p.parse_args()
    text = header()
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python3 tools/gen_bytematch_names.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"{OUT.relative_to(ROOT)}: {text.count(chr(10)) - 3} names")
    return 0


if __name__ == "__main__":
    sys.exit(main())
